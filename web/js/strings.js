  let current = "pt-BR";

  function normalize(value) {
    const text = String(value || "").replace("_", "-");
    if (text === "pt" || text === "pt-BR" || text === "pt_BR") return "pt-BR";
    if (text === "en" || text === "en-US" || text === "en_US") return "en-US";
    return "pt-BR";
  }

  function set(locale) {
    current = DICTIONARIES[normalize(locale)] ? normalize(locale) : "pt-BR";
    return current;
  }

  function t(key, values) {
    const dictionary = DICTIONARIES[current] || DICTIONARIES["pt-BR"];
    let phrase = dictionary[key] || DICTIONARIES["pt-BR"][key] || key;
    Object.keys(values || {}).forEach((name) => {
      phrase = phrase.replaceAll(`{${name}}`, String(values[name]));
    });
    return phrase;
  }

  window.MZNavI18n = { set, t, getLocale: () => current };
